    private void jbtnValidEntrActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbtnValidEntrActionPerformed
        // TODO add your handling code here:
        Date dateEntree = jDateEntree.getDate();
        
        SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");

        String date_sdf = sdf.format(dateEntree);
        
        
        Entree entree = new Entree(
                txtNBE.getText(),
                txtCode.getText(),
                Integer.parseInt(qteEntree.getText()),
                date_sdf
        );
        
        EntreeService service = new EntreeService();
        
        service.ajouterEntree(entree);
        
        chargerProduits();
        
        JOptionPane.showMessageDialog(
            this,
            "Bon d'entrée ajouter avec succès !",
            "Succès",
            JOptionPane.INFORMATION_MESSAGE
        );
        
        generateNBE();
        txtCode.setText("");
        qteEntree.setText("");
        jDateEntree.setDate(null);
        
    }//GEN-LAST:event_jbtnValidEntrActionPerformed

