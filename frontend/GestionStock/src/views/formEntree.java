    private void chargerProduits(){
        ProduitService service =
            new ProduitService();
        
        Produit[] produits =
            service.getProduits();
        
        DefaultTableModel model =
            (DefaultTableModel)
                tableProduits.getModel();
        
        model.setRowCount(0);
        
        for (Produit p : produits) {
            model.addRow(new Object[]{
            p.getNumProduit(),
            p.getDesign(),
            p.getStock()
        });
        }
        
    }
    
    private void generateNBE() {

        EntreeService service = new EntreeService();

        // récupérer le dernier numéro (ex: BE01)
        String lastNBE = service.getLastNumeroBon();

        String newNBE;

        if (lastNBE == null || lastNBE.isEmpty()) {
            newNBE = "BE01";
        } else {

            // enlever "BE"
            String numberPart = lastNBE.substring(2);

            // convertir en entier
            int num = Integer.parseInt(numberPart);

            // incrémenter
            num++;

            // formater avec 2 chiffres
            newNBE = String.format("BE%02d", num);
        }

        // afficher dans ton champ texte
        txtNBE.setText(newNBE);
    }
    
    
    
