    private void chargerEtatStock(){
        ProduitService produitService = new ProduitService();
        EntreeService entreeService = new EntreeService();
        SortieService sortieService = new SortieService();

        Produit[] produits = produitService.getProduits();
        Entree[] entrees = entreeService.getEntrees();
        Sortie[] sorties = sortieService.getSorties();

        if (produits == null) {
            produits = new Produit[0];
        }
        if (entrees == null) {
            entrees = new Entree[0];
        }
        if (sorties == null) {
            sorties = new Sortie[0];
        }

        DefaultTableModel model = (DefaultTableModel) tableEtatStock.getModel();
        model.setRowCount(0);

        for (Produit p : produits) {
            int totalEntree = 0;
            int totalSortie = 0;
            String codeProduit = p.getNumProduit();

            for (Entree e : entrees) {
                if (codeProduit.equals(e.getNumProduit())) {
                    totalEntree += e.getQteEntree();
                }
            }

            for (Sortie s : sorties) {
                if (codeProduit.equals(s.getNumProduit())) {
                    totalSortie += s.getQteSortie();
                }
            }

            int stockCalcule = p.getStock() + totalEntree - totalSortie;
            model.addRow(new Object[]{
                p.getDesign(),
                stockCalcule
            });
        }
    }

    
