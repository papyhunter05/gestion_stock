    private void chargerProduits(String recherche) {
        ProduitService service =
            new ProduitService();
        
        Produit[] produits =
            service.getProduits();
        
        DefaultTableModel model =
            (DefaultTableModel)
                tableProduits.getModel();
        
        model.setRowCount(0);

        if (produits != null) {
            for (Produit p : produits) {
                if (recherche != null && !recherche.isEmpty()) {
                    String terme = recherche.toLowerCase();
                    boolean matchCode = p.getNumProduit() != null && p.getNumProduit().toLowerCase().contains(terme);
                    boolean matchDesign = p.getDesign() != null && p.getDesign().toLowerCase().contains(terme);
                    if (!matchCode && !matchDesign) {
                        continue;
                    }
                }

                model.addRow(new Object[]{
                    p.getNumProduit(),
                    p.getDesign(),
                    p.getStock()
                });
            }
        }
        
        txtCode.setText("");
        txtDesignation.setText("");
        txtStock.setText("");
    }

    private void chargerBon() {

        EntreeService entreeService = new EntreeService();
        SortieService sortieService = new SortieService();

        Entree[] entrees = entreeService.getEntrees();
        Sortie[] sorties = sortieService.getSorties();

        String filtreProduit = null;
        String selectedProduct = (String) selecteProd.getSelectedItem();

        if (selectedProduct != null && !"Tous les produits".equals(selectedProduct)) {
            if (produitsCombo != null) {
                for (Produit p : produitsCombo) {
                    if (selectedProduct.equals(p.getDesign())) {
                        filtreProduit = p.getNumProduit();
                        break;
                    }
                }
            }
        }

        DefaultTableModel modelBon = (DefaultTableModel) tableBon.getModel();
        modelBon.setRowCount(0);

        SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");

        // 🔵 Entrées
        for (Entree e : entrees) {
            if (filtreProduit != null && !filtreProduit.equals(e.getNumProduit())) {
                continue;
            }

            String dateFormattee = e.getDateEntree();

            try {
                dateFormattee = sdf.format(sdf.parse(e.getDateEntree()));
            } catch (Exception ex) {
                dateFormattee = e.getDateEntree(); // fallback
            }

            modelBon.addRow(new Object[]{
                e.getNumBonEntree(),
                e.getNumProduit(),
                e.getQteEntree(),
                dateFormattee,
                "Entrée"
            });
        }

        // 🔴 Sorties
        for (Sortie s : sorties) {
            if (filtreProduit != null && !filtreProduit.equals(s.getNumProduit())) {
                continue;
            }

            String dateFormattee = s.getDateSortie();

            try {
                dateFormattee = sdf.format(sdf.parse(s.getDateSortie()));
            } catch (Exception ex) {
                dateFormattee = s.getDateSortie();
            }

            modelBon.addRow(new Object[]{
                s.getNumBonSortie(),
                s.getNumProduit(),
                s.getQteSortie(),
                dateFormattee,
                "Sortie"
            });
        }

        txtNumBon.setText("");
        txtDate.setDate(null);
    }
    
